"""Prose conclusion report (PDF).

`out/run-*.json` and `out/proof-*.json` are machine artifacts: correct, complete
and unreadable. This module turns the same run dict into a short A4 document a
non-technical reader can sit down with - a verdict, three to five paragraphs of
actual English explaining what happened and whether it holds up, the key figures
in a table, the two faces side by side, and an honest note on the limits.

    from facechain.report_pdf import build_conclusion, conclusion_text

    build_conclusion(run, Path("out/conclusion-abc123.pdf"))
    for para in conclusion_text(run):
        print(para)

Nothing here invents a number. Every figure is read out of `run` with .get()
chains, and a field that is missing is described as missing rather than guessed.
"""

